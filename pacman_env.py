# pacman_env.py — Οι ΚΑΝΟΝΕΣ του παιχνιδιού (χωρίς καθόλου ζωγραφική).
#
# Εδώ ζει ό,τι αποφασίζει "τι συμβαίνει": πού είναι οι τοίχοι, πού πάει ο Pacman,
# πώς κυνηγάει το φάντασμα, πόσους πόντους (reward) παίρνει ο agent.
# Η ζωγραφική είναι χωριστά, στο render.py. Έτσι μπορούμε να εκπαιδεύουμε
# τον agent πολύ γρήγορα χωρίς να ανοίγει παράθυρο.
#
# Το παιχνίδι δουλεύει σε ΓΥΡΟΥΣ (σαν σκάκι), όχι σε χρόνο:
#   1. κινείται ο Pacman  2. κινείται το φάντασμα  3. επόμενος γύρος.
# Το "πόσο γρήγορα" υπάρχει μόνο στο render.py (MOVE_EVERY).

from collections import deque   # ουρά (σαν ουρά σε ταμείο): τη χρησιμοποιεί η nearest_pellet_dir
import random                   # για τις τυχαίες κινήσεις του φαντάσματος


# ============================================================================
# Ο ΧΑΡΤΗΣ
# ============================================================================
# Κάθε χαρακτήρας είναι ένα κελί:
#   "#" = τοίχος   "." = κουκίδα   "P" = αρχική θέση Pacman   "G" = αρχική θέση φαντάσματος
# Όλες οι γραμμές ΠΡΕΠΕΙ να έχουν το ίδιο μήκος (εδώ 19 χαρακτήρες).
# Οι θέσεις γράφονται πάντα ως (γραμμή, στήλη), ξεκινώντας από το (0, 0) πάνω αριστερά.
LAYOUT = [
    "###################",
    "#........#........#",
    "#.######.#.######.#",
    "#.................#",
    "#.#.###########.#.#",
    "#.#.....P..G....#.#",
    "#.#.###########.#.#",
    "#.#...............#",
    "#.######.#.######.#",
    "#........#........#",
    "###################",
]


# ============================================================================
# ΟΙ ΚΙΝΗΣΕΙΣ (actions)
# ============================================================================
# Ο agent διαλέγει έναν αριθμό από 0 έως 3. Κάθε αριθμός λέει πόσο αλλάζει
# η θέση: (αλλαγή γραμμής, αλλαγή στήλης).
# Πάνω = γραμμή -1, γιατί οι γραμμές μετράνε από πάνω προς τα κάτω.
ACTIONS = {
    0: (-1, 0),   # πάνω
    1: (1, 0),    # κάτω
    2: (0, -1),   # αριστερά
    3: (0, 1),    # δεξιά
}


# ============================================================================
# ΤΑ REWARDS (οι "πόντοι" που μαθαίνει ο agent)
# ============================================================================
# Ο agent ΔΕΝ ξέρει αυτούς τους αριθμούς από πριν. Τους ανακαλύπτει παίζοντας
# και μαθαίνει ποιες κινήσεις φέρνουν καλό αποτέλεσμα.
REWARD_PELLET = 10     # έφαγε κουκίδα
REWARD_GHOST = -100    # τον έπιασε το φάντασμα (τέλος παιχνιδιού)
REWARD_WIN = 100       # έφαγε όλες τις κουκίδες (τέλος παιχνιδιού)
REWARD_STEP = -1       # κάθε βήμα κοστίζει λίγο, σαν ταξίμετρο: τον σπρώχνει
                       # να τελειώνει γρήγορα αντί να κάνει άσκοπες βόλτες

# Σημείωση: το reward είναι για τον agent, το score (self.score) για τον άνθρωπο
# που βλέπει την οθόνη. Είναι δύο διαφορετικά πράγματα.


# ============================================================================
# ΡΥΘΜΙΣΕΙΣ ΦΑΝΤΑΣΜΑΤΟΣ
# ============================================================================
GHOST_RANDOM = 0.2   # στο 20% των γύρων κάνει τυχαία κίνηση αντί να κυνηγάει.
                     # Χωρίς αυτό θα ήταν τέλεια προβλέψιμο και άδικα δύσκολο.
GHOST_DELAY = 5      # πόσους γύρους μένει ακίνητο στην αρχή, για να έχει
                     # ο Pacman χρόνο να απομακρυνθεί


class PacmanEnv:
    """Ένα παιχνίδι Pacman. Ο agent (ή ο άνθρωπος) μιλάει μαζί του μόνο με:
       - reset()       : ξεκίνα νέο παιχνίδι
       - step(action)  : κάνε μία κίνηση, πάρε πίσω (reward, done)
       - get_state()   : τι "βλέπει" ο agent αυτή τη στιγμή (15 αριθμοί)
    """

    def __init__(self, layout=LAYOUT):
        # Τρέχει ΜΙΑ φορά, όταν φτιάχνουμε το παιχνίδι: PacmanEnv()
        self.layout = layout
        self.rows = len(layout)        # πόσες γραμμές έχει ο χάρτης
        self.cols = len(layout[0])     # πόσες στήλες έχει ο χάρτης
        self.reset()                   # στήσε το πρώτο παιχνίδι

    # ------------------------------------------------------------------------
    def reset(self):
        # Τρέχει σε ΚΑΘΕ νέο παιχνίδι: ξαναστήνει τα πάντα από την αρχή.

        # Διαβάζουμε τον χάρτη κελί-κελί και θυμόμαστε πού είναι το καθετί.
        # Χρησιμοποιούμε set (σύνολο) γιατί το "είναι η θέση Χ τοίχος;"
        # απαντιέται αμέσως, όσο μεγάλος κι αν είναι ο χάρτης.
        self.walls = set()
        self.pellets = set()
        for r, line in enumerate(self.layout):        # r = αριθμός γραμμής
            for c, cell in enumerate(line):           # c = αριθμός στήλης
                if cell == "#":
                    self.walls.add((r, c))
                elif cell == ".":
                    self.pellets.add((r, c))
                elif cell == "P":
                    self.pacman = (r, c)
                elif cell == "G":
                    self.ghost = (r, c)

        self.score = 0            # πόντοι για την οθόνη (όχι για τον agent)
        self.done = False         # True όταν τελειώσει το παιχνίδι (νίκη ή ήττα)
        self.won = False          # True μόνο αν τελείωσε με νίκη
        self.ghost_dir = (0, 0)   # η τελευταία κατεύθυνση του φαντάσματος.
                                  # (0, 0) = δεν έχει κουνηθεί ακόμα
        self.turn = 0             # μετρητής γύρων, για το GHOST_DELAY

    # ------------------------------------------------------------------------
    def step(self, action):
        # Ένας ΓΥΡΟΣ του παιχνιδιού. Παίρνει την κίνηση (0-3) και επιστρέφει:
        #   reward : πόσο καλή ήταν η κίνηση
        #   done   : αν τελείωσε το παιχνίδι
        self.turn += 1
        reward = REWARD_STEP      # ξεκινάμε με το "κόστος" του βήματος (-1)

        # --- 1. Κίνηση του Pacman ---
        dr, dc = ACTIONS[action]            # π.χ. δεξιά → (0, 1)
        r, c = self.pacman
        new_pos = (r + dr, c + dc)
        if new_pos not in self.walls:       # σε τοίχο απλά μένει στη θέση του
            self.pacman = new_pos

        # --- Έλεγχος σύγκρουσης #1: πήγε ο Pacman πάνω στο φάντασμα; ---
        # Ελέγχουμε ΚΑΙ εδώ ΚΑΙ μετά την κίνηση του φαντάσματος, αλλιώς
        # θα μπορούσαν να "περάσουν" ο ένας μέσα από τον άλλο ανταλλάσσοντας θέσεις.
        if self.pacman == self.ghost:
            return self.lose()

        # --- 2. Φάγωμα κουκίδας ---
        if self.pacman in self.pellets:
            self.pellets.remove(self.pacman)
            reward += REWARD_PELLET         # -1 + 10 = +9 για αυτό το βήμα
            self.score += 10

        # --- 3. Νίκη: δεν έμεινε καμία κουκίδα ---
        if not self.pellets:
            self.done = True
            self.won = True
            return reward + REWARD_WIN, self.done

        # --- 4. Κίνηση του φαντάσματος (μόνο αφού περάσουν οι πρώτοι γύροι) ---
        if self.turn > GHOST_DELAY:
            self.move_ghost()

        # --- Έλεγχος σύγκρουσης #2: ήρθε το φάντασμα πάνω στον Pacman; ---
        if self.pacman == self.ghost:
            return self.lose()

        return reward, self.done

    # ------------------------------------------------------------------------
    def lose(self):
        # Τον έπιασε το φάντασμα: τέλος παιχνιδιού με μεγάλη "τιμωρία".
        self.done = True
        self.won = False
        return REWARD_GHOST, self.done

    # ------------------------------------------------------------------------
    def move_ghost(self):
        # Οι κανόνες του φαντάσματος:
        #   - Δεν περνάει από τοίχους.
        #   - Δεν κάνει αναστροφή (δεν γυρίζει από εκεί που ήρθε),
        #     εκτός αν είναι σε αδιέξοδο.
        #   - Συνήθως πάει στο διπλανό κελί που είναι πιο κοντά στον Pacman.
        #   - Με πιθανότητα GHOST_RANDOM κάνει τυχαία κίνηση.
        r, c = self.ghost

        # Η "πίσω" κατεύθυνση είναι η αντίθετη της τελευταίας του κίνησης.
        # Π.χ. αν πήγε δεξιά (0, 1), πίσω είναι αριστερά (0, -1).
        back = (-self.ghost_dir[0], -self.ghost_dir[1])

        # Μαζεύουμε όλες τις επιτρεπτές κινήσεις: (κατεύθυνση, νέα θέση)
        options = []
        for direction in ACTIONS.values():
            new_pos = (r + direction[0], c + direction[1])
            if new_pos in self.walls:
                continue                    # τοίχος → όχι
            if direction == back:
                continue                    # αναστροφή → όχι
            options.append((direction, new_pos))

        # Αδιέξοδο: δεν έμεινε καμία επιλογή, οπότε επιτρέπεται να γυρίσει πίσω.
        if not options:
            options = [(back, (r + back[0], c + back[1]))]

        if random.random() < GHOST_RANDOM:
            # random.random() δίνει έναν αριθμό από 0 έως 1.
            # Είναι κάτω από 0.2 στο 20% των φορών → τυχαία κίνηση.
            choice = random.choice(options)
        else:
            # Κυνηγητό: από τις επιλογές διαλέγουμε αυτή που φέρνει το φάντασμα
            # πιο κοντά στον Pacman. Απόσταση = πόσες γραμμές + πόσες στήλες
            # μακριά (χωρίς διαγώνιο, όπως κινούνται στον χάρτη).
            pr, pc = self.pacman
            choice = None
            best_dist = None
            for option in options:
                pos = option[1]
                dist = abs(pos[0] - pr) + abs(pos[1] - pc)
                if best_dist is None or dist < best_dist:
                    best_dist = dist
                    choice = option

        # Κάνουμε την κίνηση και θυμόμαστε την κατεύθυνση για τον επόμενο γύρο
        # (τη χρειαζόμαστε για τον κανόνα "όχι αναστροφή" και για τη get_state).
        self.ghost_dir, self.ghost = choice

    # ------------------------------------------------------------------------
    def nearest_pellet_dir(self):
        # Βρίσκει την πιο κοντινή κουκίδα ΜΕ ΤΑ ΠΟΔΙΑ (από τους διαδρόμους),
        # όχι σε ευθεία γραμμή. Έτσι μια κουκίδα πίσω από τοίχο δεν μετράει
        # σαν "κοντινή".
        #
        # Επιστρέφει δύο πράγματα:
        #   first : ποια ΠΡΩΤΗ κίνηση (0-3) πρέπει να κάνει ο Pacman για να πάει εκεί
        #   dist  : πόσα βήματα είναι μακριά
        # Αν δεν έμεινε καμία κουκίδα, επιστρέφει (None, None).
        #
        # Μέθοδος: BFS (αναζήτηση κατά πλάτος). Φαντάσου νερό που χύνεται από
        # τη θέση του Pacman και απλώνεται ένα κελί τη φορά, μόνο από διαδρόμους.
        # Η πρώτη κουκίδα που θα "βραχεί" είναι η πιο κοντινή.
        start = self.pacman
        queue = deque()      # τα κελιά που περιμένουν να τα εξετάσουμε, με σειρά άφιξης
        seen = {start}       # τα κελιά που έχουν ήδη "βραχεί", για να μην κάνουμε κύκλους

        # Πρώτο κύμα: τα 4 διπλανά κελιά (απόσταση 1).
        # Κάθε κελί στην ουρά κουβαλάει 3 πράγματα:
        #   (θέση, από ποια πρώτη κίνηση ξεκίνησε το νερό, απόσταση)
        for a in range(4):
            dr, dc = ACTIONS[a]
            nxt = (start[0] + dr, start[1] + dc)
            if nxt not in self.walls:
                seen.add(nxt)
                queue.append((nxt, a, 1))

        # Το νερό απλώνεται: βγάζουμε το παλιότερο κελί από την ουρά (popleft)
        # και προσθέτουμε τους γείτονές του με απόσταση +1. Επειδή βγαίνουν
        # με σειρά άφιξης, εξετάζουμε πρώτα όλα τα κελιά σε απόσταση 1,
        # μετά όλα σε απόσταση 2 κ.ο.κ.
        while queue:
            pos, first, dist = queue.popleft()
            if pos in self.pellets:
                return first, dist           # βρήκαμε την πιο κοντινή
            for dr, dc in ACTIONS.values():
                nxt = (pos[0] + dr, pos[1] + dc)
                if nxt not in self.walls and nxt not in seen:
                    seen.add(nxt)
                    # Ο γείτονας "κληρονομεί" την ίδια πρώτη κίνηση
                    queue.append((nxt, first, dist + 1))

        return None, None   # δεν έμεινε καμία κουκίδα

    # ------------------------------------------------------------------------
    def get_state(self):
        # Τα "ΜΑΤΙΑ" του agent: μετατρέπει την κατάσταση του παιχνιδιού σε
        # λίστα με 15 αριθμούς (input του νευρωνικού).
        #
        # Γιατί ΔΕΝ δίνουμε συντεταγμένες ή ολόκληρο τον χάρτη;
        # Γιατί θέλουμε ο agent να παίζει και σε χάρτες που δεν έχει δει.
        # Του δίνουμε μόνο "τι γίνεται γύρω μου", που σημαίνει το ίδιο σε κάθε χάρτη.
        #
        # ΠΡΟΣΟΧΗ: η σειρά των αριθμών δεν πρέπει να αλλάξει ποτέ μετά την
        # εκπαίδευση. Ο agent μαθαίνει "ο αριθμός Ν σημαίνει κάτι". Αν
        # αλλάξει θέση, θα μπερδευτεί.
        #
        # Θέσεις στη λίστα:
        #   [0-3]   τοίχος πάνω / κάτω / αριστερά / δεξιά        (0 ή 1)
        #   [4-7]   φάντασμα πάνω / κάτω / αριστερά / δεξιά μου  (0 ή 1)
        #   [8]     πόσο κοντά είναι το φάντασμα                  (0 έως 1)
        #   [9]     έρχεται το φάντασμα προς τα μένα;             (0 ή 1)
        #   [10-13] κοντινότερη κουκίδα πάνω / κάτω / αριστ. / δεξιά (0 ή 1)
        #   [14]    πόσο κοντά είναι η κοντινότερη κουκίδα        (0 έως 1)
        r, c = self.pacman
        state = []

        # --- [0-3] Τοίχοι γύρω του: 1 = τοίχος, 0 = ελεύθερο ---
        for a in range(4):
            dr, dc = ACTIONS[a]
            state.append(1 if (r + dr, c + dc) in self.walls else 0)

        # --- [4-7] Προς τα πού είναι το φάντασμα ---
        # Μπορεί να είναι 1 δύο από αυτά μαζί (π.χ. πάνω ΚΑΙ αριστερά =
        # το φάντασμα είναι διαγώνια πάνω-αριστερά). Έτσι 4 αριθμοί αρκούν
        # για κάθε πιθανή θέση.
        gr, gc = self.ghost
        state.append(1 if gr < r else 0)   # μικρότερη γραμμή = πιο πάνω
        state.append(1 if gr > r else 0)   # μεγαλύτερη γραμμή = πιο κάτω
        state.append(1 if gc < c else 0)   # μικρότερη στήλη = πιο αριστερά
        state.append(1 if gc > c else 0)   # μεγαλύτερη στήλη = πιο δεξιά

        # --- [8] Πόσο κοντά είναι το φάντασμα ---
        # Η απόσταση σε βήματα μπορεί να είναι 1, 3, 40... Αν τη βάζαμε όπως
        # είναι, ένα 40 θα "έπνιγε" τα άλλα inputs που είναι 0 ή 1 (και θα
        # έδινε τεράστια gradients). Γι' αυτό τη μετατρέπουμε σε αριθμό 0 έως 1:
        #   min(dist, 10)  → CLIPPING: πάνω από 10 βήματα όλα μετράνε "μακριά".
        #                    Διαλέξαμε 10 (και όχι π.χ. 30) ώστε όλο το εύρος
        #                    0-1 να πηγαίνει στη ζώνη κινδύνου, όπου κάθε βήμα
        #                    διαφορά έχει σημασία.
        #   / 10           → MIN-MAX: φέρνει τον αριθμό από 0 έως 1.
        #   1 - ...        → ΑΝΑΠΟΔΟΓΥΡΙΣΜΑ: κοντά = μεγάλος αριθμός ("φωνάζει"),
        #                    μακριά = 0 ("σωπαίνει", αφού 0 × weight = 0).
        # Παραδείγματα: 1 βήμα → 0.9   3 βήματα → 0.7   10+ βήματα → 0.0
        dist = abs(gr - r) + abs(gc - c)
        state.append(1 - min(dist, 10) / 10)

        # --- [9] Έρχεται το φάντασμα προς τα μένα; ---
        # "Προβλέπουμε" πού θα πάει αν συνεχίσει ίσια (με την τελευταία του
        # κατεύθυνση). Αν από εκεί θα είναι πιο κοντά μας → 1, αλλιώς → 0.
        # Στην αρχή (ghost_dir = (0, 0)) δεν έχει κουνηθεί, οπότε βγαίνει 0.
        dr, dc = self.ghost_dir
        next_ghost = (gr + dr, gc + dc)
        next_dist = abs(next_ghost[0] - r) + abs(next_ghost[1] - c)
        state.append(1 if next_dist < dist else 0)

        # --- [10-13] Προς τα πού είναι η κοντινότερη κουκίδα ---
        # Ακριβώς ΕΝΑ από τα 4 είναι 1: η πρώτη κίνηση προς την κουκίδα.
        # Αν δεν έμεινε κουκίδα (first = None), είναι όλα 0.
        first, pdist = self.nearest_pellet_dir()
        for a in range(4):
            state.append(1 if a == first else 0)

        # --- [14] Πόσο κοντά είναι η κοντινότερη κουκίδα ---
        # Ίδια λογική με το [8]: clipping στο 10, min-max, αναποδογύρισμα.
        # Αν δεν έμεινε καμία κουκίδα, βάζουμε 0 (δεν υπάρχει κάτι να "πει").
        if pdist is None:
            state.append(0)
        else:
            state.append(1 - min(pdist, 10) / 10)

        return state
